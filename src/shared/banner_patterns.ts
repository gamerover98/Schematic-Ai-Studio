/**
 * Banner patterns: which designs there are, what each looks like, and how each
 * era of the game writes them into a block entity.
 *
 * ```
 * resources/banner_patterns.json    the facts, with provenance  <- .claude/skills/mc-banner-patterns
 * scripts/gen-banner-patterns.mjs   JSON -> the table
 * src/shared/banner_patterns.ts     this file
 * ```
 *
 * In `shared/` because three places ask it and only one of them is main: the
 * renderer's block field recognises a banner to show the editor link, the MCP
 * tools describe the designs to a model, and the pipeline reads and writes the
 * NBT (`main/pipeline/banner_nbt.ts`).
 *
 * ## The three spellings, and why they are one table
 *
 * | | a layer | the list | colours |
 * |---|---|---|---|
 * | 1.8 to 1.12.2 | `{Pattern:"moj",Color:14}` | `Patterns`, plus `Base` | `15 - dye` |
 * | 1.13 to 1.20.4 | `{Pattern:"moj",Color:1}` | `Patterns` | the dye's id |
 * | 1.20.5 on | `{pattern:"minecraft:mojang",color:"orange"}` | `patterns` | the dye's name |
 *
 * The boundaries are where the game's own datafixers sit, not where a changelog
 * says something moved: `BlockEntityBannerColorFix` at DataVersion 1451 and
 * `BannerPatternFormatFix` at 3818. The first release on the far side of 3818
 * is 1.20.5; the Flattening is 1.13.
 *
 * Legacy stores the colour inverted *and* keeps the banner's own colour in
 * `Base`, because a pre-Flattening banner is one block for all sixteen colours
 * (`legacy_blocks.json` maps 176 and 177 to `white_banner` and
 * `white_wall_banner`, whatever `Base` says).
 */

import { dataVersionOf } from "./mc_versions.js";

/** One design, as the table records it. */
export interface BannerPatternRow {
  /** `mojang`: the registry id without its namespace, and its texture's name. */
  readonly id: string;
  /**
   * `moj`: what 1.8 to 1.20.4 stored as `Pattern`. `null` for the designs that
   * arrived after that spelling was retired, which is why they cannot be
   * written into an older file at all.
   */
  readonly code: string | null;
  /** The first release the design can be made in, by version name. */
  readonly since: string;
  /** What the game calls it, without the colour: `Thing`, `Chevron`. */
  readonly name: string;
  /** Where it sits on the flag, seen from the front. */
  readonly description: string;
}

