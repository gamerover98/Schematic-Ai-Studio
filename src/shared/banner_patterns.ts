/**
 * Where a person designs a banner and gets the `/give` command this app reads.
 *
 * One constant, because two places show it -- the block field and the creative
 * inventory -- and the MCP tools name it to a model that may be talking to
 * somebody without the app in front of them.
 */
export const BANNER_EDITOR_URL = "https://www.planetminecraft.com/banner/";

/** Which of the three spellings a document uses. */
export type BannerFormat = "legacy" | "coded" | "named";

export function bannerFormat(era: "legacy" | "flat", dataVersion: number | null): BannerFormat {
  if (era === "legacy") return "legacy";
  // No number on a flat document means nobody said, and the newest spelling is
  // what a file written today should carry.
  if (dataVersion !== null && dataVersion < NAMED_PATTERNS_FROM) return "coded";
  return "named";
}

const BY_ID = new Map(BANNER_PATTERNS.map((row) => [row.id, row]));
const BY_CODE = new Map(
  BANNER_PATTERNS.filter((row) => row.code !== null).map((row) => [row.code as string, row]),
);

/**
 * A design by any of the names a file or a person uses for it: `mojang`,
 * `minecraft:mojang`, or the old code `moj`.
 *
 * Ids and codes never collide -- every code is three letters or fewer and no id
 * is -- so one lookup serves both without having to be told which spelling it
 * was handed.
 */
export function bannerPattern(text: string): BannerPatternRow | null {
  const bare = text.trim().replace(/^minecraft:/, "");
  return BY_ID.get(bare) ?? BY_CODE.get(bare) ?? null;
}

/** The dye's number in the modern order, or `null` for a name that is not a dye. */
export function dyeIndex(name: string): number | null {
  const index = (BANNER_COLORS as readonly string[]).indexOf(name.trim().replace(/^minecraft:/, ""));
  return index === -1 ? null : index;
}

/** `magenta_banner` and `magenta_wall_banner`, and nothing that merely mentions banners. */
export function isBannerBlock(namespacedName: string): boolean {
  return /_(?:wall_)?banner$/.test(namespacedName.replace(/^[^:]*:/, ""));
}

/** The colour a banner block's name gives it, or `null` if it names none. */
export function bannerBlockColor(namespacedName: string): DyeName | null {
  const colour = namespacedName.replace(/^[^:]*:/, "").replace(/_(?:wall_)?banner$/, "");
  return dyeIndex(colour) === null ? null : (colour as DyeName);
}

/**
 * Whether a design exists in the version a document is for.
 *
 * A flat document with no DataVersion is taken to be current, for
 * `bannerFormat`'s reason. A legacy one with none is 1.8.8, which has only the
 * designs banners shipped with.
 */
export function patternExistsIn(
  row: BannerPatternRow,
  era: "legacy" | "flat",
  dataVersion: number | null,
): boolean {
  const since = dataVersionOf(row.since);
  if (since === null) return true;
  if (dataVersion === null) return era === "flat";
  return dataVersion >= since;
}
