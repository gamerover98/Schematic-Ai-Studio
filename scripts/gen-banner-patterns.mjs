#!/usr/bin/env node
/**
 * `resources/banner_patterns.json` -> the generated table in
 * `src/shared/banner_patterns.ts`.
 *
 * Idempotent: running it with nothing new prints "already matches" and writes
 * no bytes. If it rewrites the file every time, the ordering or the formatting
 * has drifted, and that is the bug rather than the diff.
 *
 * The same arrangement as the other six generators: only the rows between the
 * two markers are replaced, and everything else in the target -- the lookups,
 * and the prose about what each format means -- is hand-written.
 *
 * ## What it refuses
 *
 * - **A `since` that is not a release this app knows.** The label is resolved
 *   against `resources/mc_versions.json`, which is the corroborated table, and
 *   written out as the canonical name. A typo there would make a pattern
 *   available in no version at all, and the tool refusing it would say so in
 *   a sentence naming a version nobody asked about.
 * - **Two rows with one id, or one code.** The code is how 1.8 to 1.20.4 name a
 *   layer, so a duplicate reads back as the wrong design, silently.
 * - **A colour list that is not sixteen distinct names.** Its *order* is the
 *   integer every pre-1.20.5 file stores, and that order is the fact.
 *
 * What it cannot check is the prose -- whether a description is right about
 * where the design sits on the flag -- which is why the skill asks for it to be
 * written looking at the texture. See `.claude/skills/mc-banner-patterns`.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(root, "resources", "banner_patterns.json");
const VERSIONS = path.join(root, "resources", "mc_versions.json");
const TARGET = path.join(root, "src", "shared", "banner_patterns.ts");

const BEGIN = "// --- generated by scripts/gen-banner-patterns.mjs -- do not edit below -----";
const END = "// --- end generated ---------------------------------------------------------";

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

const quote = (text) => JSON.stringify(text);

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(1);
}

const source = readJson(DATA);
const versions = readJson(VERSIONS).versions;
const nameOfLabel = new Map(versions.map((row) => [row.label, row.name]));

const colors = source.colors;
if (!Array.isArray(colors) || colors.length !== 16 || new Set(colors).size !== 16) {
  fail("banner_patterns.json: colors must be sixteen distinct names, in the game's own order.");
}

const { invertedColorsBefore, namedPatternsFrom } = source.formats ?? {};
if (!Number.isInteger(invertedColorsBefore) || !Number.isInteger(namedPatternsFrom)) {
  fail("banner_patterns.json: formats.invertedColorsBefore and formats.namedPatternsFrom must be DataVersions.");
}

const ids = new Set();
const codes = new Set();
const rows = [];
for (const row of source.patterns) {
  if (ids.has(row.id)) fail(`banner_patterns.json: ${row.id} appears twice.`);
  ids.add(row.id);
  if (row.code !== null) {
    if (codes.has(row.code)) fail(`banner_patterns.json: the code ${row.code} is used twice.`);
    codes.add(row.code);
  }
  const since = nameOfLabel.get(row.since);
  if (since === undefined) {
    fail(
      `banner_patterns.json: ${row.id} says since ${row.since}, which is not a release in ` +
        `resources/mc_versions.json. Name the release by its label, as that file spells it.`,
    );
  }
  if (typeof row.name !== "string" || row.name === "" || typeof row.description !== "string" || row.description === "") {
    fail(`banner_patterns.json: ${row.id} needs a name and a description.`);
  }
  rows.push(
    [
      "  {",
      `    id: ${quote(row.id)},`,
      `    code: ${row.code === null ? "null" : quote(row.code)},`,
      `    since: ${quote(since)},`,
      `    name: ${quote(row.name)},`,
      `    description: ${quote(row.description)},`,
      "  },",
    ].join("\n"),
  );
}

const body = [
  `export const BANNER_COLORS = [${colors.map(quote).join(", ")}] as const;`,
  "",
  `export const INVERTED_COLORS_BEFORE = ${invertedColorsBefore};`,
  `export const NAMED_PATTERNS_FROM = ${namedPatternsFrom};`,
  "",
  "export const BANNER_PATTERNS: readonly BannerPatternRow[] = [",
  ...rows,
  "];",
].join("\n");

const current = readFileSync(TARGET, "utf8");
const eol = current.includes("\r\n") ? "\r\n" : "\n";
const normalized = current.replace(/\r\n/g, "\n");
const begin = normalized.indexOf(BEGIN);
const end = normalized.indexOf(END);
if (begin === -1 || end === -1) fail(`markers not found in ${TARGET}`);

const next = normalized.slice(0, begin + BEGIN.length) + "\n\n" + body + "\n\n" + normalized.slice(end);

if (next === normalized) {
  process.stdout.write(
    `already matches: ${rows.length} patterns, from ${source._source.project} at ${source._source.checkedAt}\n`,
  );
  process.exit(0);
}

writeFileSync(TARGET, eol === "\r\n" ? next.replace(/\n/g, "\r\n") : next, "utf8");
process.stdout.write(
  `wrote ${rows.length} patterns, from ${source._source.project} at ${source._source.checkedAt}\n`,
);
